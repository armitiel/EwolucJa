let wstrzyknieto = false;
export function wstrzyknijStyl(doc) {
  if (wstrzyknieto || doc.querySelector("style[data-scena3d]")) return;
  const e = doc.createElement("style");
  e.dataset.scena3d = "1";
  e.textContent = STYLE;
  doc.head.appendChild(e);
  wstrzyknieto = true;
}
